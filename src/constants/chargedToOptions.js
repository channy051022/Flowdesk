/**
 * Normalizes any chargedTo representation into a clean Array of unique non-empty strings.
 * Handles Array, JSON array string, single string, null, and undefined.
 */
export function normalizeChargedTo(val) {
  if (!val) return []
  if (Array.isArray(val)) {
    const list = []
    for (const item of val) {
      if (typeof item === 'string' && item.trim()) {
        const clean = item.trim()
        if (!list.includes(clean)) list.push(clean)
      } else if (item && typeof item === 'object' && item.chargeName) {
        const clean = String(item.chargeName).trim()
        if (clean && !list.includes(clean)) list.push(clean)
      }
    }
    return list
  }
  if (typeof val === 'string') {
    const trimmed = val.trim()
    if (!trimmed) return []
    if (trimmed.startsWith('[') && trimmed.endsWith(']')) {
      try {
        const parsed = JSON.parse(trimmed)
        if (Array.isArray(parsed)) {
          return normalizeChargedTo(parsed)
        }
      } catch {
        // Fall back to treating as single string
      }
    }
    return [trimmed]
  }
  return []
}

/**
 * Determine the group category of a given charge name
 */
export function getChargeCategory(chargeName) {
  if (!chargeName || typeof chargeName !== 'string') return 'Custom'
  if (chargeName.startsWith('MOOE-')) return 'MOOE'
  if (chargeName.startsWith('LFP-')) return 'LFP'
  return 'Custom'
}
